"""
素体の2Dモデル(body_rig.py)に付ける動き。Blender(scripts/blender/build_rig.py)と、ほかのツールへの書き出しで同じものを使う。

動きは、骨ごとのキー(コマ, 値)の並び:
- rotate: 絵の面の中の回転(度)。絵の上で反時計回りが正(キャラの右腕(絵の左)は負で上がり、左腕(絵の右)は正で上がる)
- translate: 胴(いちばん根もとの骨)の移動(絵の画素)。x は絵の右、y は絵の上が正(体ごと跳ぶ・揺れる)
コマは 1 から、24fps。最後のコマは最初と同じ姿勢にして、くり返しても途切れないようにする。
"""

from __future__ import annotations

from dataclasses import dataclass, field

FPS = 24


@dataclass(frozen=True)
class Motion:
    label: str
    frames: int
    rotate: dict[str, list[tuple[int, float]]]
    translate: dict[str, list[tuple[int, float, float]]] = field(default_factory=dict)

    def to_json(self) -> dict:
        return {
            "label": self.label, "frames": self.frames, "fps": FPS,
            "rotate": {k: [list(p) for p in v] for k, v in self.rotate.items()},
            "translate": {k: [list(p) for p in v] for k, v in self.translate.items()},
        }


